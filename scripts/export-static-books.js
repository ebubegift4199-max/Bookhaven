/* ==========================================================================
   BookHaven — Export the SQLite catalog into a static JS payload
   Writes js/bookhaven-static-data.js as:
     window.__BOOKHAVEN_STATIC_BOOKS__ = [ ...all books... ];
   Used ONLY as an offline/static fallback (e.g. GitHub Pages, file://),
   where the backend API is unreachable. When the API is reachable it is
   never loaded. Run:  npm run export:books
   ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');

const DB_PATH = path.resolve(process.env.DB_PATH || path.join(__dirname, '..', 'books.db'));
const OUT_PATH = path.join(__dirname, '..', 'js', 'bookhaven-static-data.js');

const db = new DatabaseSync(DB_PATH);
const rows = db.prepare('SELECT * FROM books ORDER BY id').all();

const books = rows.map((r) => ({
  id: r.id,
  title: r.title,
  author: r.author,
  category: r.category,
  subcategory: r.subcategory || '',
  description: r.description || '',
  cover: r.cover,
  price: r.price,
  oldPrice: r.oldPrice,
  stock: r.stock == null ? 20 : r.stock,
  rating: r.rating,
  reviews: r.reviews,
  featured: !!r.featured,
  bestseller: !!r.bestseller,
  isNew: !!r.isNew
}));

const header = [
  '/* AUTO-GENERATED by scripts/export-static-books.js — do not edit by hand. */',
  '/* Static snapshot of the BookHaven catalog for offline / static hosts', '(GitHub Pages, file://) where the backend API is not reachable. When the',
  '/* API is available it is never used. Re-generate with: npm run export:books */'
].join('\n');

const body = `window.__BOOKHAVEN_STATIC_BOOKS__ = ${JSON.stringify(books)};\n`;
fs.writeFileSync(OUT_PATH, header + '\n' + body);
console.log(`Wrote ${books.length} books to ${OUT_PATH} (${(fs.statSync(OUT_PATH).size / 1024 / 1024).toFixed(2)} MB).`);